# -----------------------------------------
# LOAD PERSONALITY PROFILE
# -----------------------------------------

def load_profile():

    if not os.path.exists(PROFILE_FILE):
        print("[-] Personality profile not found.")
        return {}

    try:
        with open(PROFILE_FILE, "r", encoding="utf-8") as file:
            profile = json.load(file)

        # فقط ویژگی‌های سبک نوشتاری را به مدل می‌دهیم.
        # عبارت‌های پرتکرار را جداگانه بررسی می‌کنیم تا مدل آن‌ها را
        # بی‌دلیل در تمام پاسخ‌ها تکرار نکند.

        allowed_fields = [
            "language",
            "tone",
            "message_length",
            "emoji_usage",
            "writing_style",
            "affection_style",
            "humor_style"
        ]

        clean_profile = {
            key: profile[key]
            for key in allowed_fields
            if key in profile
        }

        return clean_profile

    except (json.JSONDecodeError, OSError) as error:

        print(f"[-] Profile loading error: {error}")
        return {}


# -----------------------------------------
# FORMAT CHAT HISTORY
# -----------------------------------------

def format_history(history):

    formatted = []

    for item in history or []:

        sender = item.get("sender")
        message = item.get("text", "").strip()

        if not message:
            continue

        if sender == "me":
            name = "من"

        elif sender == "partner":
            name = "طرف مقابل"

        else:
            continue

        formatted.append(f"{name}: {message}")

    return "\n".join(formatted)


# -----------------------------------------
# GET PREVIOUS REPLIES
# -----------------------------------------

def get_previous_replies(history):

    replies = []

    for item in history or []:

        if item.get("sender") == "me":

            text = item.get("text", "").strip()

            if text:
                replies.append(text)

    return replies[-MAX_PREVIOUS_REPLIES:]


